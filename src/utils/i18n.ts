const LANGUAGE_STORAGE_KEY = 'sham_perfume_selected_lang';

export function getInitialLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY) as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }
    // Auto-detect browser language
    const browserLang = navigator.language.slice(0, 2).toLowerCase();
    if (browserLang === 'ar') return 'ar';
    if (browserLang === 'fr') return 'fr';
    if (browserLang === 'es') return 'es';
    if (browserLang === 'it') return 'it';
    if (browserLang === 'de') return 'de';
    if (browserLang === 'ru') return 'ru';
    if (browserLang === 'zh') return 'zh';
    if (browserLang === 'tr') return 'tr';
    if (browserLang === 'fa') return 'fa';
    if (browserLang === 'en') return 'en';
  } catch (e) {
    // fallback
  }
  return 'ar'; // Default Arabic as requested
}

export function saveLanguage(lang: SupportedLanguage) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    const config = SUPPORTED_LANGUAGES.find((l) => l.code === lang);
    if (config) {
      document.documentElement.dir = config.dir;
      document.documentElement.lang = config.code;
    }
  } catch (e) {
    console.error('Failed to save language preference', e);
  }
}

export function t(key: TranslationKey, lang: SupportedLanguage): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.ar[key] || key;
}
